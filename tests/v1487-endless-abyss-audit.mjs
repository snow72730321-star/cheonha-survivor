import fs from "node:fs";
import assert from "node:assert/strict";
const balance=fs.readFileSync("js/data/balance-v14.js","utf8");
const combat=fs.readFileSync("js/systems/combat-runtime.js","utf8");
const power=fs.readFileSync("js/systems/combat-power-v14-7-7.js","utf8");
const abyss=fs.readFileSync("js/systems/abyss-mode-v14-8-7.js","utf8");
const index=fs.readFileSync("index.html","utf8");
const save=fs.readFileSync("js/core/save-manager.js","utf8");
assert.match(balance,/abyss:\{rank:5,name:"무한나락"[\s\S]*?endless:true/);
assert.match(balance,/desc:"무제한 · 15분 생존 목표 · 권장 전투력 100,000"/);
assert.match(power,/abyss:100000/);
assert.match(combat,/!diff\.endless&&elapsed>=runDuration/);
assert.match(combat,/state==="playing"&&!d\.endless/);
assert.match(abyss,/TARGET=900/);
assert.match(abyss,/nextBossAt=360;nextAbyssMiniAt=180/);
assert.match(abyss,/nextBossAt\+=180/);
assert.match(abyss,/nextAbyssMiniAt\+=45/);
assert.match(abyss,/elapsed>=720\?2:1/);
assert.match(abyss,/post\*\.18/);
assert.match(abyss,/post\*\.12/);
assert.match(save,/bestAbyssTime/);
assert.match(index,/abyss-mode-v14-8-7\.js/);
// 15분 적 압박이 수라보다 명백히 높고, 영원+25 기준에서도 생존 중심이 되도록 한 수치 감사.
const elapsed=900, rank=5, scaleTime=180, enemyHp=3.05, enemyDamage=2.55;
const late=1;
const progressionHp=1+Math.pow(late,1.75)*(.58+rank*.12);
const progressionDamage=1+Math.pow(late,1.45)*(.26+rank*.075);
const stageProgress=elapsed/180;
const abyssHp=1+Math.pow(stageProgress,1.42)*.18;
const abyssDamage=1+Math.pow(stageProgress,1.28)*.15;
const banditHp=25*(1+elapsed/scaleTime)*enemyHp*progressionHp*abyssHp;
const banditDamage=10*enemyDamage*progressionDamage*abyssDamage;
assert.ok(banditHp>2500,`15m bandit hp ${banditHp}`);
assert.ok(banditDamage>85,`15m bandit damage ${banditDamage}`);
console.log("v14.8.7 endless abyss audit: OK",{banditHp:Math.round(banditHp),banditDamage:Math.round(banditDamage)});
