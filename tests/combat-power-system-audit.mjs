import fs from "node:fs";
import vm from "node:vm";
import assert from "node:assert/strict";
const src=fs.readFileSync("js/systems/combat-power-v14-7-7.js","utf8");
const enhance=(level,grade)=>{
  const scale={common:.82,rare:.90,epic:.98,unique:1.07,legendary:1.17,mythic:1.30,eternal:1.46}[grade]||1;
  let value=1;for(let i=1;i<=Math.max(0,Math.min(25,level||0));i++){const base=i%5===0?.072:.036,high=i>=16?(i>=21?1.22:1.10):1;value*=1+base*scale*high}return value;
};
const context={console,account:{equipped:{},weapons:[]}};context.window=context;context.CheonHaForgeV13={enhancementMultiplier:enhance};
vm.createContext(context);vm.runInContext(src,context);
const cp=context.CombatPowerSystem;
assert.deepEqual({...cp.benchmark()},{legendary15:20000,mythic0:20000,sura:20000});
const l15={grade:"legendary",level:15,baseDamageMul:1.54,potentials:[]};
const m0={grade:"mythic",level:0,baseDamageMul:1.66,potentials:[]};
assert.equal(cp.value(l15),20000);assert.equal(cp.value(m0),20000);
assert.ok(cp.value({...l15,ability:"han"})>20000);
assert.ok(cp.value({...l15,potentials:[{key:"damage",value:.2,grade:"legendary"}]})>20000);
assert.equal(cp.pressure(20000).tier,0);assert.equal(cp.pressure(18000).tier,1);assert.equal(cp.pressure(15000).tier,2);assert.equal(cp.pressure(10000).tier,3);
assert.equal(cp.recommended("gosu"),13000);
console.log("combat-power-system-audit: OK",cp.benchmark());
